/**
 * Checks if a specific route path is allowed for a user role.
 */
export function isRouteAllowedForRole(role: UserRole | string | null | undefined, path: string): boolean {
  if (!role) return false;
  const normalizedRole = (role as UserRole);
  const allowed = ROLE_PERMITTED_ROUTES[normalizedRole];
  if (!allowed) return false;

  // Exact match or subpath match
  const cleanPath = path.split('?')[0].split('#')[0];
  if (cleanPath === '/' || cleanPath === '') {
    return allowed.includes(ROUTES.HOME) || allowed.includes('/');
  }
  return allowed.some(r => r === cleanPath || (r !== '/' && cleanPath.startsWith(r)));
}
